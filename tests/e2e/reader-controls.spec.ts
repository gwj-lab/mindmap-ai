import { _electron as electron, expect, test } from '@playwright/test';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { randomUUID } from 'node:crypto';
import { WorkspaceStore } from '../../src/main/workspace-store.js';
import { contentHash } from '../../src/shared/content.js';
import { DEFAULT_CONCEPT_SETTINGS, type ConceptRecord } from '../../src/shared/concepts.js';

test('project folds, editor drag/close and long-text questions with an independent website and saved template', async () => {
  test.setTimeout(90000);
  const root = await mkdtemp(path.join(tmpdir(), 'mindmap-reader-controls-'));
  const profile = await mkdtemp(path.join(tmpdir(), 'mindmap-reader-controls-profile-'));
  let app: Awaited<ReturnType<typeof electron.launch>> | undefined;
  try {
    const store = new WorkspaceStore(root);
    const initial = await store.initialize('交互验收', '项目一');
    const other = await store.createProject('项目二', null);
    await store.switchProject(initial.project.manifest.projectId);
    const now = new Date().toISOString();
    const first = '残差是观测值与预测值之差。' + '这段解释用于验证大段文字的答疑选取。'.repeat(18);
    const second = '第二段补充上下文，并进一步说明模型与原文之间的关系。'.repeat(12);
    const quote = `${first}\n${second}`;
    const body = `# 模型\n\n${first}\n\n${second}`;
    const metadata = { id: 'source', title: '模型', provider: 'chatgpt' as const, sourceUrl: 'https://chatgpt.com/c/source', sourceMessageId: 'source', contentHash: await contentHash(body), capturedAt: now, updatedAt: now };
    await store.answers.write({ metadata, body });
    await store.answers.write({ metadata: { ...metadata, id: 'candidate-source', title: '待整理节点' }, body });
    const id = randomUUID();
    const record: ConceptRecord = { id, answerId: `concept-${id}`, title: '残差', provider: 'chatgpt', status: 'ready', prompt: '', tabId: `concept-tab-${id}`, createdAt: now,
      references: [initial.project.manifest.projectId, other.manifest.projectId].map((projectId) => ({ projectId, sourceAnswerId: 'source', sourceTitle: '模型', sourceUrl: metadata.sourceUrl, sourceMessageId: 'source', selection: { text: '残差', sentence: '残差是观测值与预测值之差。', prefix: '', suffix: '是观测值与预测值之差。' } })) };
    await store.answers.write({ metadata: { ...metadata, id: record.answerId, conceptId: id, title: '残差' }, body: '残差概念笔记。' });
    await writeFile(path.join(root, 'concepts.json'), JSON.stringify({ settings: { ...DEFAULT_CONCEPT_SETTINGS, provider: 'doubao', background: true }, records: [record] }));
    await store.saveActive({ ...initial.project, state: { ...initial.project.state, candidates: [{ id: 'candidate', answerId: 'candidate-source', title: '待整理节点', extractionMode: 'single', children: [], createdAt: now }] }, mindmap: { uid: 'root', text: '项目一', children: [{ uid: 'note', text: '模型', answerId: 'source', children: [] }] } });
    app = await electron.launch({ args: ['.', `--user-data-dir=${profile}`] });
    await app.evaluate(({ dialog }, root) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [root] }); }, root);
    const page = await app.firstWindow(); const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message));
    await page.getByRole('button', { name: '打开工作区', exact: true }).first().click();
    const tray = page.getByRole('tabpanel', { name: '候选节点', exact: true });
    const candidates = tray.locator(':scope > .tray-category');
    await expect(candidates).toContainText('项目一');
    await candidates.locator(':scope > summary').click(); await expect(tray.getByText('待整理节点', { exact: true })).not.toBeVisible();
    await candidates.locator(':scope > summary').click(); await expect(tray.getByText('待整理节点', { exact: true })).toBeVisible();
    const conceptGroups = tray.locator('.concept-library .tray-project');
    await expect(conceptGroups).toHaveCount(2);
    await expect(conceptGroups.nth(0).locator(':scope > summary')).toContainText('项目一');
    await expect(conceptGroups.nth(1).locator(':scope > summary')).toContainText('项目二');
    await conceptGroups.nth(1).locator(':scope > summary').click(); await expect(conceptGroups.nth(1).locator('.concept-node-card')).not.toBeVisible();
    const conceptCategory = tray.locator('.concept-library > details');
    await conceptCategory.locator(':scope > summary').click(); await expect(conceptGroups.nth(0).locator('.concept-node-card')).not.toBeVisible();
    await conceptCategory.locator(':scope > summary').click();
    await page.locator('.mindmap-canvas .smm-node', { hasText: '模型' }).dblclick();
    const reader = page.getByLabel('回答阅读器');
    await reader.getByRole('button', { name: '收起概念侧栏' }).click();
    await reader.getByRole('button', { name: '编辑', exact: true }).click();
    const divider = reader.getByRole('separator', { name: '调整 Markdown 与预览宽度' });
    const before = (await reader.locator('.answer-editor').boundingBox())!.width;
    const bounds = (await divider.boundingBox())!;
    await page.mouse.move(bounds.x + 4, bounds.y + bounds.height / 2); await page.mouse.down();
    await page.mouse.move(bounds.x + 110, bounds.y + bounds.height / 2, { steps: 8 }); await page.mouse.up();
    expect((await reader.locator('.answer-editor').boundingBox())!.width).toBeGreaterThan(before + 70);
    const editor = reader.locator('.cm-content'); await editor.click(); await page.keyboard.press('Control+End'); await page.keyboard.type('\n\n保留编辑草稿。');
    await reader.getByRole('button', { name: '关闭编辑页面' }).click();
    await expect(reader.locator('.answer-editor')).toHaveCount(0);
    await expect(reader.locator('.markdown-preview')).toContainText('保留编辑草稿。');
    await reader.getByRole('button', { name: '编辑', exact: true }).click(); await expect(editor).toContainText('保留编辑草稿。');
    await reader.getByRole('button', { name: '保存', exact: true }).click();
    await expect(reader.locator('.answer-pane > footer')).toContainText('内容已保存');
    await reader.getByRole('button', { name: '关闭编辑页面' }).click();
    const selectLong = async (): Promise<void> => reader.locator('.markdown-preview').evaluate((root) => {
      const paragraphs = root.querySelectorAll('p');
      const range = document.createRange(); range.setStart(paragraphs[0]!.firstChild!, 0); range.setEnd(paragraphs[1]!.firstChild!, paragraphs[1]!.firstChild!.textContent!.length);
      document.getSelection()!.removeAllRanges(); document.getSelection()!.addRange(range);
      paragraphs[1]!.dispatchEvent(new MouseEvent('mouseup', { bubbles: true, button: 0 }));
    });
    await selectLong(); await reader.locator('.selection-ask-button').click();
    const dialog = page.getByRole('dialog', { name: '对原文提问' });
    await expect(dialog.locator('blockquote')).toContainText(second);
    await dialog.locator('.question-settings > summary').click();
    await dialog.getByLabel('答疑网页模型').selectOption('deepseek');
    const template = '围绕 {title} 分析以下原文：{selection}';
    await dialog.getByLabel('答疑初始提示词').fill(template);
    await dialog.getByRole('button', { name: '保存答疑设置' }).click();
    await expect(dialog.getByRole('button', { name: '应用到本次问题' })).toBeEnabled();
    await dialog.getByRole('button', { name: '应用到本次问题' }).click();
    await expect(dialog.getByLabel('自定义问题')).toHaveValue(`围绕 模型 分析以下原文：${quote}`);
    await dialog.getByLabel('自定义问题').fill('只用于本次的长文本追问。');
    await app.evaluate(async ({ session }) => {
      await session.fromPartition('persist:provider-deepseek').protocol.handle('https', () => new Response(`<!doctype html><meta charset="utf-8"><textarea placeholder="给 DeepSeek 发送消息"></textarea><div role="button" class="ds-button--primary ds-button--circle">发送</div><script>document.querySelector('[role=button]').onclick=()=>{document.body.dataset.sentPrompt=document.querySelector('textarea').value;const answer=document.createElement('div');answer.className='ds-message';answer.dataset.messageId='generated';answer.innerHTML='<div class="ds-assistant-message-main-content"><p>长文本的答疑回答。</p></div>';document.body.append(answer);};</script>`, { headers: { 'Content-Type': 'text/html; charset=utf-8' } }));
    });
    const artifact = path.resolve('artifacts/reader-controls'); await mkdir(artifact, { recursive: true });
    await dialog.screenshot({ path: path.join(artifact, 'question-settings.png') });
    await dialog.getByRole('button', { name: '发送问题' }).click(); await expect(dialog).not.toBeVisible();
    await expect.poll(async () => (await page.evaluate(() => window.mindmapAI.concepts.get())).records.find((record) => record.kind === 'qa')?.status, { timeout: 15000 }).toBe('ready');
    const library = await page.evaluate(() => window.mindmapAI.concepts.get());
    const qa = library.records.find((record) => record.kind === 'qa')!;
    expect(qa.provider).toBe('deepseek'); expect(qa.prompt).toBe('只用于本次的长文本追问。');
    expect(qa.references[0]!.selection.text).toBe(quote);
    expect(library.questionSettings).toEqual({ provider: 'deepseek', prompt: template });
    expect(library.settings.provider).toBe('doubao');
    await reader.getByRole('button', { name: /^查看答疑：/ }).click();
    await expect(reader.getByLabel('答疑批注', { exact: true })).toContainText('长文本的答疑回答。');
    await reader.getByRole('button', { name: /定位原文/ }).click();
    await expect(reader.locator('.concept-range-chip[data-kind="qa"]').first()).toBeVisible();
    await reader.screenshot({ path: path.join(artifact, 'long-selection.png') });
    await selectLong(); await reader.locator('.selection-ask-button').click();
    await expect(dialog.getByLabel('自定义问题')).toHaveValue(`围绕 模型 分析以下原文：${quote}`);
    await dialog.getByRole('button', { name: '关闭提问框' }).click();
    expect(errors).toEqual([]);
  } finally {
    await app?.close(); await rm(root, { recursive: true, force: true }); await rm(profile, { recursive: true, force: true });
  }
});
