import { _electron as electron, expect, test } from '@playwright/test';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { WorkspaceStore } from '../../src/main/workspace-store.js';
import { createNodeAttachment } from '../../src/main/node-attachments.js';
import { startS3Server } from '../support/s3-server.js';

test('finds cross-project and content matches, creates/imports attachments, and syncs via the real S3 UI', async () => {
  test.setTimeout(120000);
  const root = await mkdtemp(path.join(tmpdir(), 'mindmap-search-s3-ui-'));
  const profile = await mkdtemp(path.join(tmpdir(), 'mindmap-search-s3-profile-'));
  const downloads = await mkdtemp(path.join(tmpdir(), 'mindmap-search-s3-downloads-'));
  const imports = await mkdtemp(path.join(tmpdir(), 'mindmap-search-s3-imports-'));
  const server = await startS3Server(); let app: Awaited<ReturnType<typeof electron.launch>> | undefined;
  try {
    const file = path.join(imports, 'existing.markdown'); const importedBody = '# 导入的文档\n\n这是本机 Markdown 内容。'; await writeFile(file, importedBody);
    const store = new WorkspaceStore(root); const opened = await store.initialize('功能验收', '项目一');
    const answer = await createNodeAttachment(store.answers, '正文笔记'); await store.answers.write({ ...answer, body: '# 文档\n\n搜索正文专用关键句。' });
    const first = { ...opened.project, mindmap: { uid: 'root', text: '项目一', children: [{ uid: 'attach-target', text: '附件节点', children: [] }, { uid: 'content-target', text: '正文笔记', answerId: answer.metadata.id, children: [] }] } };
    await store.saveActive(first);
    const other = await store.createProject('项目二', null);
    await store.saveActive({ ...other, mindmap: { uid: 'other-root', text: '项目二', children: [{ uid: 'collapsed', text: '折叠的父节点', expand: false, children: [{ uid: 'hidden', text: '隐藏搜索节点', children: [] }] }] } });
    await store.switchProject(opened.project.manifest.projectId);
    app = await electron.launch({ args: ['.', `--user-data-dir=${profile}`] });
    await app.firstWindow();
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]!.setSize(1080, 760));
    await app.evaluate(({ dialog }, paths) => { dialog.showOpenDialog = async (options) => ({ canceled: false, filePaths: [options.title?.includes('导入') ? paths.file : options.title?.includes('空文件夹') ? paths.downloads : paths.root] }); }, { file, downloads, root });
    const page = await app.firstWindow(); const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message));
    await page.getByRole('button', { name: '打开工作区', exact: true }).first().click();
    const search = page.getByRole('textbox', { name: '搜索节点', exact: true });
    expect((await search.boundingBox())!.width).toBeGreaterThan(120);
    const headerWidth = await page.locator('.topbar').evaluate((header) => ({ width: header.clientWidth, scroll: header.scrollWidth }));
    expect(headerWidth.scroll).toBeLessThanOrEqual(headerWidth.width);
    await search.fill('隐藏搜索');
    await page.getByRole('option', { name: /隐藏搜索节点/ }).click();
    await expect(page.getByLabel('项目路径')).toContainText('项目二');
    await expect(page.locator('.mindmap-canvas .smm-node', { hasText: '隐藏搜索节点' })).toBeVisible();
    await search.fill('专用关键句');
    await expect(page.getByRole('listbox', { name: '搜索结果' }).getByRole('option')).toHaveCount(0);
    await page.getByLabel('同时搜索附加文档正文').check();
    await page.getByRole('option', { name: /正文笔记/ }).click();
    await expect(page.getByLabel('项目路径')).toContainText('项目一');
    const target = page.locator('.mindmap-canvas .smm-node', { hasText: '附件节点' });
    await target.click({ button: 'right' });
    await page.getByRole('menuitem', { name: '新增空白文档' }).click();
    const reader = page.getByLabel('回答阅读器'); const editor = reader.locator('.cm-content');
    await expect(editor).toBeVisible(); await editor.fill('# 自定义文档\n\n新增正文。');
    await reader.getByRole('button', { name: '保存', exact: true }).click();
    await expect(reader.locator('footer')).toContainText('内容已保存');
    const mapPath = path.join(root, 'projects', opened.project.manifest.projectId, 'mindmap.json');
    const originalId = JSON.parse(await readFile(mapPath, 'utf8')).children[0].answerId as string;
    await reader.getByRole('button', { name: '关闭阅读窗口' }).click();
    await target.click({ button: 'right' }); page.once('dialog', (dialog) => void dialog.accept());
    await page.getByRole('menuitem', { name: '导入 Markdown 文档' }).click();
    await expect(reader.locator('.markdown-preview')).toContainText('这是本机 Markdown 内容。');
    const map = JSON.parse(await readFile(mapPath, 'utf8'));
    expect(map.children[0].answerId).not.toBe(originalId);
    expect((await page.evaluate((id) => window.mindmapAI.project.readAnswer(id), originalId))?.body).toContain('新增正文。');
    expect(await readFile(file, 'utf8')).toBe(importedBody);
    await reader.getByRole('button', { name: '关闭阅读窗口' }).click();
    await page.getByRole('button', { name: 'S3 同步', exact: true }).click();
    const sync = page.getByRole('dialog', { name: 'S3 同步', exact: true });
    await sync.getByLabel('S3 服务地址', { exact: true }).fill(server.endpoint);
    await sync.getByLabel('S3 存储桶', { exact: true }).fill('test-bucket');
    await sync.getByLabel('S3 同步目录', { exact: true }).fill('ui-workspace');
    await sync.getByLabel('使用路径形式寻址（MinIO 等兼容服务）').check();
    await sync.getByLabel('S3 Access Key', { exact: true }).fill('test-access');
    await sync.getByLabel('S3 Secret Key', { exact: true }).fill('test-secret');
    await sync.getByRole('button', { name: '保存 S3 配置' }).click();
    await expect(sync.getByRole('status')).toContainText('S3 配置已保存');
    await sync.getByRole('button', { name: '测试连接' }).click(); await expect(sync.getByRole('status')).toContainText('连接成功');
    await sync.getByRole('button', { name: '上传当前工作区' }).click(); await expect(sync.getByRole('status')).toContainText('已上传');
    await sync.screenshot({ path: 'test-results/s3-sync-settings.png' });
    await sync.getByRole('button', { name: '下载云端工作区' }).click();
    await expect(sync).not.toBeVisible();
    await expect.poll(async () => (await page.evaluate(() => window.mindmapAI.workspace.listRecent()))[0]?.path).toBe(downloads);
    const restored = await new WorkspaceStore(downloads).load();
    expect(restored.workspace.workspaceId).toBe(opened.workspace.workspaceId);
    expect(restored.project.mindmap.children[0]?.answerId).toBe(map.children[0].answerId);
    expect(server.requests.every((request) => request.signed)).toBe(true);
    expect(errors).toEqual([]);
  } finally { await app?.close(); await server.close(); await Promise.all([root, profile, downloads, imports].map((directory) => rm(directory, { recursive: true, force: true }))); }
});
