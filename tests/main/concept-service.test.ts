import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterEach, expect, test, vi } from "vitest";
import { ConceptService } from "../../src/main/concept-service.js";
import { DEFAULT_CONCEPT_SETTINGS, DEFAULT_QUESTION_SETTINGS, questionPrompt, questionRequestSchema, conceptRequestSchema } from "../../src/shared/concepts.js";
const projectId = "2cb66115-270c-4107-89e0-f61508c14d2b";
const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map((root) => rm(root, { recursive: true, force: true }))); });
async function service() { const root = await mkdtemp(path.join(tmpdir(), "mindmap-concept-")); roots.push(root); return { root, service: new ConceptService(root, vi.fn()) }; }
const selection = { text: "残差", sentence: "残差是观测值与预测值之差。", prefix: "", suffix: "是观测值与预测值之差。" };
test("question settings persist independently and long quotes survive completion and retry", async () => {
  const { root, service: store } = await service();
  const source = await store.saveSource({ provider: "chatgpt", sourceUrl: "https://chatgpt.com/c/source", sourceMessageId: "source", markdown: '长篇原文。'.repeat(100) });
  await store.settings({ ...DEFAULT_CONCEPT_SETTINGS, provider: "doubao" });
  await store.questionSettings({ ...DEFAULT_QUESTION_SETTINGS, provider: "kimi", prompt: '请分析 {title} 中的 {selection}，上下文是 {sentence}。' });
  const reopened = new ConceptService(root, vi.fn());
  expect((await reopened.get()).questionSettings?.provider).toBe("kimi");
  expect((await reopened.get()).settings.provider).toBe("doubao");
  const selected = { text: '长篇原文。'.repeat(100), sentence: '长篇原文。'.repeat(100), prefix: '', suffix: '' };
  const request = { sourceAnswerId: source.metadata.id, sourceTitle: '模型', selection: selected };
  expect(conceptRequestSchema.safeParse(request).success).toBe(false);
  const question = questionPrompt(request, (await reopened.get()).questionSettings);
  const job = await reopened.prepareQuestion(questionRequestSchema.parse({ ...request, question }), projectId);
  expect(job.record.provider).toBe('kimi'); expect(job.record.title).toHaveLength(160);
  expect(job.record.references[0]!.selection.text).toBe(selected.text);
  await reopened.fail(job.record.id, '重试');
  await reopened.questionSettings({ ...DEFAULT_QUESTION_SETTINGS, provider: 'deepseek' });
  const retry = await reopened.retry(job.record.id);
  expect(retry.record.provider).toBe('kimi'); expect(retry.record.prompt).toBe(question);
  await reopened.complete(job.record.id, { provider: 'kimi', sourceUrl: 'https://www.kimi.com/chat/answer', sourceMessageId: 'answer', markdown: '长文本答疑回答' });
  const stored = (await new ConceptService(root, vi.fn()).get()).records[0]!;
  expect(stored.references[0]!.selection.text).toBe(selected.text);
  expect((await reopened.answers.read(stored.answerId))?.body).toContain(selected.text);
});
test("saves concept Markdown, bidirectional links, tags and same-context reuse", async () => {
  const { root, service: store } = await service();
  const source = await store.saveSource({ provider: "yuanbao", sourceUrl: "https://yuanbao.tencent.com/chat/source", sourceMessageId: "source", markdown: "# 回归模型\n\n残差是观测值与预测值之差。" });
  const request = { sourceAnswerId: source.metadata.id, sourceTitle: "回归模型", selection };
  const job = await store.prepare(request, projectId);
  await store.complete(job.record.id, { provider: "yuanbao", sourceUrl: "https://yuanbao.tencent.com/chat/concept", sourceMessageId: "concept", markdown: "# 残差\n\n$$\ne=y-\\hat y\n$$\n\n解释正文。" });
  const concept = await store.answers.read(job.record.answerId);
  expect(concept?.metadata).toMatchObject({ conceptId: job.record.id, tags: ["概念"], provider: "yuanbao" });
  expect(concept?.body).toContain(`](${source.metadata.id}.md)`);
  expect((await store.answers.read(source.metadata.id))?.body).toContain(`](${job.record.answerId}.md)`);
  await store.writeEdited({ ...source, body: "编辑后的正文" }, (answer) => store.answers.write(answer));
  expect((await store.answers.read(source.metadata.id))?.body).toContain("编辑后的正文");
  expect((await store.answers.read(source.metadata.id))?.body).toContain(`](${job.record.answerId}.md)`);
  expect((await store.prepare(request, projectId))).toMatchObject({ reused: true, record: { id: job.record.id, status: "ready" } });
  const distinct = await store.prepare({ ...request, sourceTitle: "数值算法", selection: { ...selection, sentence: "残差表示方程代入后的不平衡量。" } }, projectId);
  expect(distinct.record.id).not.toBe(job.record.id);
  expect(JSON.parse(await readFile(path.join(root, "concepts.json"), "utf8")).records).toHaveLength(2);
  const reopened = await new ConceptService(root, vi.fn()).get();
  expect(reopened.records[0]!.status).toBe("ready");
  expect(reopened.records[1]!).toMatchObject({ status: "failed", error: "上次生成被中断，请重试" });
});
test("persists settings, failure retry, trash restore and safe names", async () => {
  const { root, service: store } = await service();
  await store.settings({ ...DEFAULT_CONCEPT_SETTINGS, provider: "doubao", background: true });
  const source = await store.saveSource({ provider: "chatgpt", sourceUrl: "https://chatgpt.com/c/source", sourceMessageId: "source", markdown: "回答正文" });
  const job = await store.prepare({ sourceAnswerId: source.metadata.id, sourceTitle: "模型", selection }, projectId);
  expect(job).toMatchObject({ background: true, record: { provider: "doubao" } });
  await store.fail(job.record.id, "请登录");
  const retry = await store.retry(job.record.id);
  expect(retry.record.tabId).not.toBe(job.record.tabId);
  await store.fail(job.record.id, "测试失败");
  await store.update(job.record.id, "trash");
  expect((await store.get()).records[0]!.status).toBe("trash");
  await store.update(job.record.id, "restore");
  expect((await store.get()).records[0]!.status).toBe("failed");
  expect((await new ConceptService(root, vi.fn()).get()).settings.provider).toBe("doubao");
  await expect(store.answers.read("../outside")).rejects.toThrow("Invalid answer id");
});

test("stores questions as annotations, keeps custom prompts on retry and distinguishes questions from concepts", async () => {
  const { root, service: store } = await service();
  const payload = { provider: "kimi" as const, sourceUrl: "https://www.kimi.com/chat/source", sourceMessageId: "source", markdown: "# 回归模型\n\n残差是观测值与预测值之差。" };
  const source = await store.saveSource(payload);
  const request = { sourceAnswerId: source.metadata.id, sourceTitle: "回归模型", selection };
  const concept = await store.prepare(request, projectId);
  const question = "为什么残差均值接近零？\n请结合一个例子解释。";
  const job = await store.prepareQuestion({ ...request, question }, projectId);
  expect(job.record).toMatchObject({ kind: "qa", prompt: question });
  expect(job.record.id).not.toBe(concept.record.id);
  await store.fail(job.record.id, "暂时失败");
  const retry = await store.retry(job.record.id);
  expect(retry.record.prompt).toBe(question);
  await store.complete(job.record.id, { ...payload, sourceMessageId: "qa", markdown: "# 答疑\n\n带截距的最小二乘回归使残差之和为零。\n\n| 模型 | 残差和 |\n| --- | --- |\n| 带截距 | 0 |" });
  const note = await store.answers.read(job.record.answerId);
  expect(note?.metadata).toMatchObject({ annotationId: job.record.id, tags: ["答疑"] });
  expect(note?.metadata.conceptId).toBeUndefined();
  expect(note?.body).toContain("> 为什么残差均值接近零？");
  expect((await store.answers.read(source.metadata.id))?.body).toContain("## 答疑批注");
  expect((await store.saveSource(payload)).metadata.id).toBe(source.metadata.id);
  expect((await store.prepareQuestion({ ...request, question }, projectId)).reused).toBe(true);
  expect((await store.prepareQuestion({ ...request, question: "另一个问题" }, projectId)).reused).toBe(false);
  await store.writeEdited({ ...source, body: source.body + "\n\n新增段落。" }, (answer) => store.answers.write(answer));
  expect((await store.answers.read(source.metadata.id))?.body).toContain(`](${job.record.answerId}.md)`);
  expect((await new ConceptService(root, vi.fn()).get()).records.find((record) => record.id === job.record.id)).toMatchObject({ kind: "qa", status: "ready", prompt: question });
});
